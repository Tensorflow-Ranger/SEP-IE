"""Score rank1 (LR)/rank2 (MLP) on the v8 Qwen-GENERATED inline-edit test:
same 40 held-out base prompts and same redundant/missing methodology as
v6/v7 (scripts/score_v7_combined.py), but here the inline rewrites were
generated BY Qwen3-8B itself (given the original prompt, the change to make,
and a style instruction) instead of hand-authored by the researcher. See
gen_v8_all40.py (scratchpad) for the generation prompt.

Purpose: check whether the effect seen with hand-authored inline edits
(missing detail pulls P(ambiguous) down more than a redundant restatement)
still holds -- or gets stronger/weaker -- when the edits are model-generated,
ruling out hand-authoring artifacts as the explanation.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import joblib
import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data_utils import load_activation_bundle

ACTS_DIR = ROOT / "activations_detail_test_v8_qwen_generated"
RESULTS_DIR = ROOT / "results_v8_qwen_generated"
RANK1_PATH = ROOT / "models" / "rank1_lr_layer20_pca100_ccb_heval.joblib"
RANK2_PATH = ROOT / "models" / "rank2_mlp_layer22_pca100_ccb_heval.joblib"
DATA_PATH = ROOT / "data" / "detail_addition_probe_test_v8_qwen_generated.jsonl"


def H(p: np.ndarray) -> np.ndarray:
    p = np.clip(p, 1e-12, 1 - 1e-12)
    return -(p * np.log2(p) + (1 - p) * np.log2(1 - p))


def main() -> None:
    RESULTS_DIR.mkdir(exist_ok=True)
    acts, _labels, _groups, _token_lens, meta_rows = load_activation_bundle(ACTS_DIR)
    id_to_row = {m["id"]: i for i, m in enumerate(meta_rows)}

    no_change = {}
    for line in DATA_PATH.open(encoding="utf-8"):
        if not line.strip():
            continue
        r = json.loads(line)
        if "qwen_made_no_change" in r:
            no_change[r["id"]] = r["qwen_made_no_change"]

    rank1 = joblib.load(RANK1_PATH)
    rank2 = joblib.load(RANK2_PATH)
    rank1_layer = json.load(open(ROOT / "models" / "rank1_lr_layer20_pca100_ccb_heval.json"))["layer"]
    rank2_layer = json.load(open(ROOT / "models" / "rank2_mlp_layer22_pca100_ccb_heval.json"))["layer"]
    print(f"[score_v8] rank1 (LR) layer={rank1_layer}, rank2 (MLP) layer={rank2_layer}")

    base_ids = sorted({m["id"].rsplit("__", 1)[0] for m in meta_rows}, key=lambda x: int(x.split("_")[-1]))

    table = []
    for base in base_ids:
        row = {"base_id": base, "ambiguity_types": ",".join(meta_rows[id_to_row[f"{base}__baseline"]]["ambiguity_types"])}
        for variant in ("baseline", "redundant", "missing"):
            i = id_to_row[f"{base}__{variant}"]
            x1 = acts[i, rank1_layer, :].reshape(1, -1)
            x2 = acts[i, rank2_layer, :].reshape(1, -1)
            p1 = float(rank1.predict_proba(x1)[0, list(rank1.classes_).index(1)])
            p2 = float(rank2.predict_proba(x2)[0, list(rank2.classes_).index(1)])
            row[f"rank1_p_amb_{variant}"] = round(p1, 4)
            row[f"rank2_p_amb_{variant}"] = round(p2, 4)
            if variant != "baseline":
                row[f"{variant}_qwen_no_change"] = no_change.get(f"{base}__{variant}", None)
        table.append(row)

    with (RESULTS_DIR / "comparison_table.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(table[0].keys()))
        w.writeheader()
        w.writerows(table)

    n_red_nochange = sum(1 for row in table if row.get("redundant_qwen_no_change"))
    n_mis_nochange = sum(1 for row in table if row.get("missing_qwen_no_change"))
    print(f"\n[score_v8] Qwen made NO change in: redundant {n_red_nochange}/{len(table)}, missing {n_mis_nochange}/{len(table)}")

    print(f"\n=== rank1 (LR) / rank2 (MLP), P(ambiguous), n={len(table)}, QWEN-GENERATED inline edits ===")
    print(f"  {'base_id':14s} {'type':22s} {'LR b/r/m':20s} {'MLP b/r/m':20s}")
    for row in table:
        print(f"  {row['base_id']:14s} {row['ambiguity_types']:22s} "
              f"{row['rank1_p_amb_baseline']:.2f}/{row['rank1_p_amb_redundant']:.2f}/{row['rank1_p_amb_missing']:.2f}          "
              f"{row['rank2_p_amb_baseline']:.2f}/{row['rank2_p_amb_redundant']:.2f}/{row['rank2_p_amb_missing']:.2f}")

    def deltas(key, subset=None):
        rows = table if subset is None else [r for r in table if r["base_id"] in subset]
        d_red = np.array([row[f"{key}_redundant"] - row[f"{key}_baseline"] for row in rows])
        d_mis = np.array([row[f"{key}_missing"] - row[f"{key}_baseline"] for row in rows])
        return d_red, d_mis

    def run_summary(name, key, subset=None, label="all"):
        d_red, d_mis = deltas(key, subset)
        diff = d_mis - d_red
        t = stats.ttest_rel(d_mis, d_red)
        w = stats.wilcoxon(d_mis, d_red)
        s = {
            "label": label,
            "mean_delta_redundant": float(d_red.mean()), "std_delta_redundant": float(d_red.std()),
            "n_redundant_down": int((d_red < 0).sum()),
            "mean_delta_missing": float(d_mis.mean()), "std_delta_missing": float(d_mis.std()),
            "n_missing_down": int((d_mis < 0).sum()),
            "n_total": len(d_red),
            "mean_missing_minus_redundant": float(diff.mean()),
            "n_missing_lower_than_redundant": int((diff < 0).sum()),
            "paired_ttest_p": float(t.pvalue),
            "wilcoxon_p": float(w.pvalue),
        }
        print(f"  [{label}] {name:24s} redundant: mean={s['mean_delta_redundant']:+.4f}+/-{s['std_delta_redundant']:.4f} "
              f"({s['n_redundant_down']}/{s['n_total']} down)   "
              f"missing: mean={s['mean_delta_missing']:+.4f}+/-{s['std_delta_missing']:.4f} "
              f"({s['n_missing_down']}/{s['n_total']} down)")
        print(f"    paired (missing - redundant): mean={s['mean_missing_minus_redundant']:+.4f}, "
              f"{s['n_missing_lower_than_redundant']}/{s['n_total']} prompts where missing pulled lower, "
              f"paired-t p={s['paired_ttest_p']:.4f}, wilcoxon p={s['wilcoxon_p']:.4f}")
        return s

    print(f"\n=== Summary (n={len(table)}, negative = probe says 'less ambiguous') ===")
    summary = {}
    for name, key in [("rank1_lr_p_ambiguous", "rank1_p_amb"), ("rank2_mlp_p_ambiguous", "rank2_p_amb")]:
        summary[name] = run_summary(name, key, subset=None, label="all_n40")

    # clean subset: drop prompts where Qwen made no change on EITHER variant (a no-op
    # dilutes that condition's delta toward 0 by construction, not signal)
    clean_ids = {row["base_id"] for row in table
                 if not row.get("redundant_qwen_no_change") and not row.get("missing_qwen_no_change")}
    print(f"\n=== Clean subset (drop no-op generations, n={len(clean_ids)}) ===")
    summary_clean = {}
    for name, key in [("rank1_lr_p_ambiguous", "rank1_p_amb"), ("rank2_mlp_p_ambiguous", "rank2_p_amb")]:
        summary_clean[name] = run_summary(name, key, subset=clean_ids, label=f"clean_n{len(clean_ids)}")

    # ---- entropy view ----
    entropy_summary = {}
    print(f"\n=== Entropy H(p) shift (bits; negative = probe MORE confident), n={len(table)} ===")
    for name, key in [("rank1_lr", "rank1_p_amb"), ("rank2_mlp", "rank2_p_amb")]:
        Hb = H(np.array([row[f"{key}_baseline"] for row in table]))
        Hr = H(np.array([row[f"{key}_redundant"] for row in table]))
        Hm = H(np.array([row[f"{key}_missing"] for row in table]))
        d_red, d_mis = Hr - Hb, Hm - Hb
        entropy_summary[name] = {
            "mean_deltaH_redundant": float(d_red.mean()), "n_redundant_more_confident": int((d_red < 0).sum()),
            "mean_deltaH_missing": float(d_mis.mean()), "n_missing_more_confident": int((d_mis < 0).sum()),
            "n_total": len(d_red),
        }
        s = entropy_summary[name]
        print(f"  {name:14s} redundant: mean={s['mean_deltaH_redundant']:+.4f} ({s['n_redundant_more_confident']}/{s['n_total']} more confident)   "
              f"missing: mean={s['mean_deltaH_missing']:+.4f} ({s['n_missing_more_confident']}/{s['n_total']} more confident)")

    # ---- comparison to v7 hand-authored, for the headline question: does confidence rise or fall? ----
    v7_path = ROOT / "results_v7_combined" / "summary.json"
    comparison = {}
    if v7_path.exists():
        v7 = json.load(open(v7_path))
        for name, key in [("rank1_lr_p_ambiguous", "rank1_lr"), ("rank2_mlp_p_ambiguous", "rank2_mlp")]:
            v7s = v7["raw_p"][name]
            v8s = summary[name]
            comparison[name] = {
                "v7_hand_authored_ttest_p": v7s["paired_ttest_p"], "v7_hand_authored_wilcoxon_p": v7s["wilcoxon_p"],
                "v7_hand_authored_mean_missing_minus_redundant": v7s["mean_missing_minus_redundant"],
                "v8_qwen_generated_ttest_p": v8s["paired_ttest_p"], "v8_qwen_generated_wilcoxon_p": v8s["wilcoxon_p"],
                "v8_qwen_generated_mean_missing_minus_redundant": v8s["mean_missing_minus_redundant"],
            }
        print(f"\n=== v7 (hand-authored) vs v8 (Qwen-generated) head-to-head, same 40 prompts ===")
        for name, c in comparison.items():
            print(f"  {name}:")
            print(f"    hand-authored: mean(missing-redundant)={c['v7_hand_authored_mean_missing_minus_redundant']:+.4f}, "
                  f"t-p={c['v7_hand_authored_ttest_p']:.4f}, wilcoxon-p={c['v7_hand_authored_wilcoxon_p']:.4f}")
            print(f"    qwen-generated: mean(missing-redundant)={c['v8_qwen_generated_mean_missing_minus_redundant']:+.4f}, "
                  f"t-p={c['v8_qwen_generated_ttest_p']:.4f}, wilcoxon-p={c['v8_qwen_generated_wilcoxon_p']:.4f}")

    with (RESULTS_DIR / "summary.json").open("w", encoding="utf-8") as f:
        json.dump({
            "raw_p": summary, "raw_p_clean_subset": summary_clean, "entropy": entropy_summary,
            "n_redundant_no_change": n_red_nochange, "n_missing_no_change": n_mis_nochange,
            "comparison_to_v7_hand_authored": comparison,
        }, f, indent=2)

    print(f"\n[score_v8] wrote results -> {RESULTS_DIR}")


if __name__ == "__main__":
    main()
